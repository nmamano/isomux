// Writes shared/public-tlds.ts: the top-level names of the ICANN section of
// the Public Suffix List, IDN names in punycode form. It leaves out the
// special-use names: an .onion or .arpa name is no public address.
//
//   bun scripts/gen-public-tlds.ts [path to public_suffix_list.dat]
//
// The default path is the Debian/Ubuntu publicsuffix package. The list is
// also at https://publicsuffix.org/list/public_suffix_list.dat.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const source =
  process.argv[2] ?? "/usr/share/publicsuffix/public_suffix_list.dat";
const icann = readFileSync(source, "utf8")
  .split("===BEGIN ICANN DOMAINS===")[1]
  ?.split("===END ICANN DOMAINS===")[0];
if (!icann) throw new Error(`${source}: no ICANN section`);

const SPECIAL_USE = new Set(["arpa", "onion"]);
const names = new Set<string>();
for (const raw of icann.split("\n")) {
  const line = raw.trim();
  if (!line || line.startsWith("//") || /[.*!]/.test(line)) continue;
  if (SPECIAL_USE.has(line)) continue;
  names.add(new URL(`http://x.${line}`).hostname.slice(2));
}

let body = "";
let line = "";
for (const name of [...names].sort()) {
  if (line && line.length + name.length + 1 > 78) {
    body += line + "\n";
    line = "";
  }
  line += (line ? " " : "") + name;
}
body += line;

const date = new Date().toISOString().slice(0, 10);
writeFileSync(
  join(import.meta.dir, "../shared/public-tlds.ts"),
  `// Generated by scripts/gen-public-tlds.ts on ${date} from the ICANN section
// of the Public Suffix List (https://publicsuffix.org). Do not edit by hand.
// A name missing here keeps a value masked (isPublicAddressValue), so an old
// list fails safe.

export const PUBLIC_TLDS: ReadonlySet<string> = new Set(
  \`
${body}
\`
    .split(/\\s+/)
    .filter(Boolean),
);
`,
);
console.log(`${names.size} names`);
